// 1) 변수 age에 62 넣기
const age =19
// 2) age가 60 이상이면 → `당신의 나이는 ${age}이군요! 당신은 노인입니다.` 출력
if(age>=60){
    console.log(`당신의 나이는 ${age}이군요! 당신은 노인입니다.` );
    
}else if(age>=18){
    // 3) else if: 18 이상이면 → '…당신은 성인입니다.' 출력
    console.log(`당신의 나이는 ${age}이군요! 당신은 성인입니다.` );
    
}else{
    // 4) else: 나머지는 → '…당신은 미성년자입니다.' 출력
    console.log(`당신의 나이는 ${age}이군요! 당신은 미성년자입니다.` );

}
