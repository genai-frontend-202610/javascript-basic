// 1) 변수 day에 3 넣기
const day = 4

// 2) switch (day)
switch (day) {
    //    case 1 → "Monday" 출력 후 break
    case 1:
        console.log("월요일");
        break;
    case 2:
        console.log("화요일");
        break;
    case 3:
        console.log("수요일");
        break;
    case 4:
        console.log("목요일");
        break;
    case 5:
        console.log("금요일");
        break;
    default:
        console.log("유효하지 않은 요일");

}
//    case 3 → "Wednesday"
//    case 4 → "Thursday"
//    case 5 → "Friday"
//    default → "Invalid day" (유효하지 않은 요일)
